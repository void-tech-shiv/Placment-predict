import html
import uuid
from datetime import datetime
from pathlib import Path

from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer


class ReportGenerator:
    def __init__(self):
        self.base_dir = Path(__file__).resolve().parent.parent
        self.report_dir = self.base_dir / "reports"
        self.report_dir.mkdir(parents=True, exist_ok=True)

    def generate_report(self, student_data, prediction, confidence):
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
        filename = f"placement_report_{timestamp}_{uuid.uuid4().hex[:6]}.pdf"
        filepath = self.report_dir / filename
        document = SimpleDocTemplate(str(filepath)); styles = getSampleStyleSheet()
        story = [Paragraph("<b>Placement Predict Report</b>",styles["Title"]),Spacer(1,20),Paragraph(f"Generated On: {datetime.now().strftime('%d-%m-%Y %I:%M:%S %p')}",styles["Normal"]),Spacer(1,20),Paragraph("<b>Student Details</b>",styles["Heading2"]),Spacer(1,10)]
        for key,value in student_data.items(): story.append(Paragraph(f"<b>{html.escape(str(key))}</b>: {html.escape(str(value))}",styles["Normal"]))
        story.extend([Spacer(1,20),Paragraph("<b>Prediction Result</b>",styles["Heading2"]),Spacer(1,10),Paragraph(f"<b>Prediction:</b> {html.escape(str(prediction))}",styles["Normal"]),Paragraph(f"<b>Confidence:</b> {html.escape(str(confidence))} %" if confidence is not None else "<b>Confidence:</b> Not Available",styles["Normal"]),Spacer(1,30),Paragraph("This report was automatically generated by Placement Predict.",styles["Italic"])])
        document.build(story); return filename,str(filepath)
